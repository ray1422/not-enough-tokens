export const LOCALES = [
  ['zh-TW', '繁體中文'],
  ['en', 'English'],
];

let current = 'en';

export function resolveLocale(pref) {
  if (pref && STRINGS[pref]) return pref;
  const nav = (navigator.languages || [navigator.language || 'en']).map((l) => l.toLowerCase());
  return nav.some((l) => l.startsWith('zh')) ? 'zh-TW' : 'en';
}

export function setLocale(pref) {
  current = resolveLocale(pref);
  document.documentElement.lang = current;
  return current;
}

export function t(key, vars) {
  let s = STRINGS[current][key] ?? STRINGS.en[key] ?? key;
  if (vars) s = s.replace(/\{(\w+)\}/g, (_, k) => (vars[k] ?? `{${k}}`));
  return s;
}

// Static markup: <span data-i18n="key"> and data-i18n-title="key".
export function translateDom(root = document) {
  for (const el of root.querySelectorAll('[data-i18n]')) el.textContent = t(el.dataset.i18n);
  for (const el of root.querySelectorAll('[data-i18n-title]')) el.title = t(el.dataset.i18nTitle);
}
